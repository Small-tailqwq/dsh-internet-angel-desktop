#!/usr/bin/env node
/**
 * Publish the art manifest as content-addressed runtime files instead of
 * base64 inside the client bundle.
 *
 * Every manifest asset is copied byte-for-byte to
 * `assets/runtime/<sha256>.<ext>`, listed in `assets/runtime/manifest.json`
 * (served by the node half's allowlisted route and fingerprinted with the
 * build), and exported from `src/client/art.generated.ts` as a small
 * descriptor whose URL resolves against the host base at runtime.
 *
 * The DSH 0.2 desktop shell serves `/plugins/` bundles with `no-store`, so a
 * 24 MB bundle made every reload re-read and re-parse all artwork.
 *
 * Usage: node scripts/write-skin-art.mjs [--check]
 */
import { createHash } from 'node:crypto'
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, extname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const RUNTIME_DIR = resolve(ROOT, 'assets/runtime')
const RUNTIME_MANIFEST = resolve(RUNTIME_DIR, 'manifest.json')
const EXPORT_NAME = /^[A-Z][A-Z0-9_]*$/
const MIME = new Map([
  ['.png', 'image/png'],
  ['.ogg', 'audio/ogg'],
  ['.wav', 'audio/wav'],
  ['.woff2', 'font/woff2'],
])
const KINDS = new Set(['scene', 'ornament', 'tile', 'icon', 'font', 'audio'])

const check = process.argv.includes('--check')

/** PNG dimensions straight from the IHDR chunk; other media report 0x0 as before. */
function dimensions(bytes, ext) {
  if (ext !== '.png') return { width: 0, height: 0 }
  const signature = '89504e470d0a1a0a'
  if (bytes.subarray(0, 8).toString('hex') !== signature || bytes.subarray(12, 16).toString('latin1') !== 'IHDR') {
    throw new Error('not a PNG with a leading IHDR chunk')
  }
  return { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) }
}

function load() {
  const manifest = JSON.parse(readFileSync(resolve(ROOT, 'assets/art.manifest.json'), 'utf8'))
  if (manifest.schemaVersion !== 1 || manifest.output !== 'src/client/art.generated.ts' || !Array.isArray(manifest.assets)) {
    throw new Error('assets/art.manifest.json: unexpected schema')
  }
  const ids = new Set()
  const exportNames = new Set()
  return manifest.assets.map((asset, index) => {
    const label = `assets[${index}]`
    if (typeof asset.id !== 'string' || asset.id === '' || ids.has(asset.id)) throw new Error(`${label}.id is missing or duplicated`)
    if (typeof asset.exportName !== 'string' || !EXPORT_NAME.test(asset.exportName) || exportNames.has(asset.exportName)) {
      throw new Error(`${label}.exportName is invalid or duplicated`)
    }
    if (!KINDS.has(asset.kind)) throw new Error(`${label}.kind is invalid`)
    for (const key of ['creator', 'license', 'source']) {
      if (typeof asset.attribution?.[key] !== 'string' || asset.attribution[key] === '') throw new Error(`${label}.attribution.${key} is required`)
    }
    if (typeof asset.source !== 'string' || !asset.source.startsWith('assets/source/') || asset.source.includes('..')) {
      throw new Error(`${label}.source must stay inside assets/source/`)
    }
    ids.add(asset.id)
    exportNames.add(asset.exportName)
    const ext = extname(asset.source).toLowerCase()
    const mime = MIME.get(ext)
    if (mime === undefined) throw new Error(`${label}.source has an unsupported type: ${asset.source}`)
    const bytes = readFileSync(resolve(ROOT, asset.source))
    const sha256 = createHash('sha256').update(bytes).digest('hex')
    let size
    try {
      size = dimensions(bytes, ext)
    } catch (error) {
      throw new Error(`${asset.source}: ${error.message}`)
    }
    return { ...asset, ext, mime, bytes, sha256, file: `${sha256}${ext}`, ...size }
  }).sort((a, b) => a.id.localeCompare(b.id))
}

function render(assets) {
  const lines = [
    '/** GENERATED by scripts/write-skin-art.mjs. Edit assets/art.manifest.json and source assets instead. */',
    "import { skinAsset } from './skin-asset.ts'",
    '',
  ]
  for (const asset of assets) {
    lines.push(`/** ${asset.id}: ${asset.source}. */`)
    lines.push(`export const ${asset.exportName} = skinAsset(${JSON.stringify(asset.file)}, ${JSON.stringify(asset.mime)}, ${asset.width}, ${asset.height})`)
    lines.push('')
  }
  return lines.join('\n')
}

const assets = load()
const files = [...new Set(assets.map(asset => asset.file))].sort()
const generated = render(assets)
const runtimeManifest = `${JSON.stringify(files, null, 2)}\n`
const output = resolve(ROOT, 'src/client/art.generated.ts')

if (check) {
  const stale = []
  if (!existsSync(output) || readFileSync(output, 'utf8') !== generated) stale.push('src/client/art.generated.ts')
  if (!existsSync(RUNTIME_MANIFEST) || readFileSync(RUNTIME_MANIFEST, 'utf8').replaceAll('\r\n', '\n') !== runtimeManifest) {
    stale.push('assets/runtime/manifest.json')
  }
  for (const asset of assets) {
    const target = resolve(RUNTIME_DIR, asset.file)
    if (!existsSync(target)) stale.push(`assets/runtime/${asset.file} (${asset.source})`)
  }
  if (stale.length > 0) {
    console.error(`skin art is stale; run node scripts/write-skin-art.mjs\n  ${stale.join('\n  ')}`)
    process.exitCode = 1
  } else {
    console.log(`skin art current: ${assets.length} assets, ${files.length} runtime files`)
  }
} else {
  mkdirSync(RUNTIME_DIR, { recursive: true })
  for (const asset of assets) {
    const target = resolve(RUNTIME_DIR, asset.file)
    if (!existsSync(target)) copyFileSync(resolve(ROOT, asset.source), target)
  }
  // Files no asset references any more would still ship and be served.
  const keep = new Set([...files, 'manifest.json'])
  const orphans = readdirSync(RUNTIME_DIR).filter(file => !keep.has(file))
  writeFileSync(RUNTIME_MANIFEST, runtimeManifest)
  writeFileSync(output, generated)
  console.log(`skin art written: ${assets.length} assets, ${files.length} runtime files`)
  if (orphans.length > 0) console.warn(`unreferenced files in assets/runtime/ (delete them):\n  ${orphans.join('\n  ')}`)
}
