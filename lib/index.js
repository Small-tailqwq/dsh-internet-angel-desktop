/**
* Host half of Internet Angel Desktop: serves the packaged artwork, audio and
* fonts that the browser half references by content hash.
*
* Paths come from the shipped allowlist, never from disk traversal. Files are
* public, immutable presentation assets (no user data), so they carry a
* one-year immutable cache. The route is owned by the activation and released
* with it.
*/
/** Must match `SKIN_ASSET_ROUTE` in src/client/skin-asset.ts. */
const SKIN_ASSET_PREFIX = "/skin-assets/internet-angel-desktop";
const CONTENT_TYPES = {
	png: "image/png",
	ogg: "audio/ogg",
	wav: "audio/wav",
	woff2: "font/woff2"
};
const FILE_NAME = /^[a-f0-9]{64}\.(png|ogg|wav|woff2)$/;
/** One satisfiable `bytes=` range, or undefined for a full response. */
function parseRange(header, size) {
	if (header === void 0) return void 0;
	const match = /^bytes=(\d*)-(\d*)$/.exec(header.trim());
	if (match === null || match[1] === "" && match[2] === "") return void 0;
	let start;
	let end;
	if (match[1] === "") {
		start = Math.max(0, size - Number(match[2]));
		end = size - 1;
	} else {
		start = Number(match[1]);
		end = match[2] === "" ? size - 1 : Math.min(size - 1, Number(match[2]));
	}
	return start <= end && start < size ? {
		start,
		end
	} : null;
}
/**
* Build the request handler for one asset directory.
* @param directory - Folder holding the allowlisted files.
* @param allowlist - `<sha256>.<ext>` names from the runtime manifest.
*/
function createSkinAssetHandler(directory, allowlist) {
	const allowed = new Set(allowlist);
	return async (req, res) => {
		if (req.method !== "GET" && req.method !== "HEAD") {
			res.writeHead(405, { Allow: "GET, HEAD" }).end();
			return;
		}
		const pathname = new URL(req.url ?? "/", "http://localhost").pathname;
		const file = pathname.slice(36);
		const extension = FILE_NAME.exec(file)?.[1];
		if (!pathname.startsWith(`/skin-assets/internet-angel-desktop/`) || !allowed.has(file) || extension === void 0) {
			res.writeHead(404).end();
			return;
		}
		let bytes;
		try {
			bytes = await readFile(new URL(file, directory));
		} catch (error) {
			if (error.code !== "ENOENT") throw error;
			res.writeHead(404).end();
			return;
		}
		const etag = `"${file.slice(0, 64)}"`;
		const headers = {
			"Content-Type": CONTENT_TYPES[extension],
			"Cache-Control": "public, max-age=31536000, immutable",
			"X-Content-Type-Options": "nosniff",
			"Accept-Ranges": "bytes",
			ETag: etag
		};
		if (req.headers["if-none-match"]?.split(",").some((value) => value.trim().replace(/^W\//, "") === etag || value.trim() === "*")) {
			res.writeHead(304, headers).end();
			return;
		}
		const range = parseRange(req.headers.range, bytes.length);
		if (range === null) {
			res.writeHead(416, {
				...headers,
				"Content-Range": `bytes */${bytes.length}`
			}).end();
			return;
		}
		const body = range === void 0 ? bytes : bytes.subarray(range.start, range.end + 1);
		res.writeHead(range === void 0 ? 200 : 206, {
			...headers,
			"Content-Length": body.length,
			...range === void 0 ? {} : { "Content-Range": `bytes ${range.start}-${range.end}/${bytes.length}` }
		});
		res.end(req.method === "HEAD" ? void 0 : body);
	};
}
/** Serve this package's assets while the skin is enabled. */
function apply(ctx) {
	const handler = createSkinAssetHandler(new URL("../assets/runtime/", import.meta.url), manifest_default);
	ctx.inject(["webServer"], (webCtx) => {
		const server = webCtx.get("webServer");
		webCtx.effect(() => server.register({
			kind: "prefix",
			path: SKIN_ASSET_PREFIX,
			handler
		}), "internet-angel-desktop: packaged assets");
	});
}
