export type UiText = string | (() => string)
export const isChinese = (): boolean => typeof document !== 'undefined' && document.documentElement.lang.toLowerCase().startsWith('zh')
export const resolveText = (text: UiText): string => typeof text === 'function' ? text() : text

export function t(key: string, ...values: Array<string | number>): string {
  const template = isChinese() ? key : english[key] ?? key
  return template.replace(/\{(\d+)\}/g, (match, index: string) => String(values[Number(index)] ?? match))
}

type Binding = () => void
const bindings = new WeakMap<Element, Map<string, Binding>>()
const listeners = new Set<() => void>()

function bind(element: Element, key: string, update?: Binding): void {
  let entries = bindings.get(element)
  if (update) {
    if (!entries) { entries = new Map(); bindings.set(element, entries) }
    entries.set(key, update)
    element.setAttribute('data-ngo-i18n', '')
  } else {
    entries?.delete(key)
    if (!entries?.size) element.removeAttribute('data-ngo-i18n')
  }
}

export function setText(element: Element, text: UiText): void {
  const node = document.createTextNode(resolveText(text))
  element.replaceChildren(node)
  // Bind the text node, so later-appended inputs and icons survive locale changes.
  bind(element, 'text', typeof text === 'function' ? () => {
    if (node.parentNode === element) node.data = text()
  } : undefined)
}

export function setAttr(element: Element, name: string, text: UiText): void {
  const update = () => element.setAttribute(name, resolveText(text))
  update()
  bind(element, name, typeof text === 'function' ? update : undefined)
}

export function onLocaleChange(listener: () => void): () => void {
  listeners.add(listener)
  return () => { listeners.delete(listener) }
}

export function installLocale(): () => void {
  let previous = isChinese()
  const refresh = () => {
    const next = isChinese()
    if (next === previous) return
    previous = next
    for (const element of document.querySelectorAll('[data-ngo-i18n]')) {
      for (const update of bindings.get(element)?.values() ?? []) update()
    }
    for (const listener of listeners) listener()
  }
  const observer = new MutationObserver(refresh)
  observer.observe(document.documentElement, { attributes: true, attributeFilter: ['lang'] })
  return () => {
    observer.disconnect()
    for (const element of document.querySelectorAll('[data-ngo-i18n]')) {
      bindings.delete(element)
      element.removeAttribute('data-ngo-i18n')
    }
  }
}
